#!/usr/bin/env node
// Generates crates/auri-cli/src/presets.rs from the reference catalog.
//
// Only the numbers and the short names are copied. The reference's prose
// descriptions are AGPL and stay out of this MIT repository.
//
// Usage: node tools/gen-presets.mjs
//        AURI_OPEN_AURI_DIR=/path/to/open-auri node tools/gen-presets.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const reference = resolve(
  process.env.AURI_OPEN_AURI_DIR ?? join(root, '..', 'open-auri'),
);

const catalog = await import(
  pathToFileURL(join(reference, 'src/catalog/presets.mjs')).href
);

/** Official curves in display order, then Neutro. */
const presets = [...catalog.OFFICIAL_PRESETS, catalog.NEUTRO];

const BAND_NAMES = { PK: 'Pk', LS: 'Ls', HS: 'Hs', LP: 'Lp', HP: 'Hp' };

function number(value) {
  if (!Number.isFinite(value)) {
    throw new Error(`expected a finite number, got ${value}`);
  }
  return Number.isInteger(value) ? `${value}.0` : `${value}`;
}

function band(b) {
  if (b.kind === 'OFF') {
    return 'Band::Off';
  }
  const name = BAND_NAMES[b.kind];
  if (name === undefined) {
    throw new Error(`unsupported band kind ${b.kind}`);
  }
  return (
    `Band::${name} { freq_hz: ${number(b.freqHz)}, ` +
    `gain_db: ${number(b.gainDb)}, q_factor: ${number(b.qFactor)} }`
  );
}

const entries = presets
  .map((preset) => {
    const bands = preset.bands
      .map((b) => `            ${band(b)},`)
      .join('\n');
    const crc = preset.crc.toString(16).padStart(4, '0');
    return [
      '    Preset {',
      `        id: ${JSON.stringify(preset.id)},`,
      `        label: ${JSON.stringify(preset.label)},`,
      `        preamp_db: ${number(preset.preampDb)},`,
      `        crc: 0x${crc}u16,`,
      '        bands: [',
      bands,
      '        ],',
      '    },',
    ].join('\n');
  })
  .join('\n');

const output = `//! The official Kuba Auri presets, generated by \`tools/gen-presets.mjs\`.
//!
//! Only the numbers and the short names live here: the reference catalog's
//! prose is not copied. Regenerate with \`node tools/gen-presets.mjs\`.

use auri_codec::{BAND_COUNT, Band};

/// One official curve.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Preset {
    /// Stable identifier used by \`--preset\`.
    pub id: &'static str,
    /// Display name.
    pub label: &'static str,
    /// Preamp in dB.
    pub preamp_db: f64,
    /// CRC-16 the cable expects for this curve.
    pub crc: u16,
    /// The ten bands, in the order the wire wants them.
    pub bands: [Band; BAND_COUNT],
}

impl Preset {
    /// The curve this preset represents.
    #[must_use]
    pub fn curve(&self) -> crate::curve::CurveFile {
        crate::curve::CurveFile {
            preamp_db: self.preamp_db,
            eq_bands: self.bands.to_vec(),
        }
    }
}

/// The eleven official presets in display order, then Neutro.
pub const PRESETS: [Preset; ${presets.length}] = [
${entries}
];

/// Looks a preset up by its stable id.
#[must_use]
pub fn find(id: &str) -> Option<&'static Preset> {
    PRESETS.iter().find(|preset| preset.id == id)
}

/// The position of a preset in \`PRESETS\`, for the TUI's \`{\`/\`}\` cycling.
#[must_use]
pub fn index_of(id: &str) -> Option<usize> {
    PRESETS.iter().position(|preset| preset.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;
    use auri_codec::encode_payload;
    use auri_gate::{GateOptions, Profile, gate_for_write};

    #[test]
    fn every_official_curve_encodes_to_its_official_crc() {
        for preset in &PRESETS {
            let payload = encode_payload(&preset.bands, preset.preamp_db)
                .unwrap_or_else(|error| panic!("{}: {error}", preset.id));
            let len = payload.len();
            let stored = u16::from_le_bytes([payload[len - 2], payload[len - 1]]);
            assert_eq!(stored, preset.crc, "{}", preset.id);
        }
    }

    #[test]
    fn every_official_curve_passes_the_standard_gate() {
        for preset in &PRESETS {
            let verdict = gate_for_write(
                &preset.bands,
                preset.preamp_db,
                GateOptions::for_write(false, Profile::Standard),
            );
            assert!(
                verdict.ok,
                "{} is refused: {:?}",
                preset.id,
                verdict.reasons.iter().map(|reason| reason.code).collect::<Vec<_>>()
            );
        }
    }

    #[test]
    fn the_neutral_preset_is_the_neutral_curve() {
        let preset = find("neutro").expect("neutro");
        let curve = preset.curve();
        let neutral = crate::curve::CurveFile::neutral();
        assert_eq!(curve.preamp_db, neutral.preamp_db);
        assert_eq!(curve.eq_bands, neutral.eq_bands);
        assert_eq!(preset.crc, 0x4fff);
    }

    #[test]
    fn ids_are_unique_and_unknown_ids_are_none() {
        for (index, preset) in PRESETS.iter().enumerate() {
            assert!(
                !PRESETS[..index].iter().any(|other| other.id == preset.id),
                "duplicate id {}",
                preset.id
            );
            assert_eq!(find(preset.id).map(|found| found.id), Some(preset.id));
        }
        assert!(find("nope").is_none());
        assert!(find("Auri").is_none(), "labels are not ids");
    }
}
`;

writeFileSync(join(root, 'crates/auri-cli/src/presets.rs'), output);
console.log(
  `wrote ${presets.length} presets to crates/auri-cli/src/presets.rs`,
);
